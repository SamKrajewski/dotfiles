#!/usr/bin/env python3
"""Collects the change under review into .review/tmp/change.json.

Supports git repositories, jj (Jujutsu) workspaces, and plain diff files.
The output is the single input every later step reads, so it carries the
SHAs, branch, changed files with per-file stats, the unified diff (minus
skipped files), commits with trailers, the PR when `gh` can see one, the
prior review state for re-reviews, and a triage depth suggestion.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys

import review_common as rc

GENERATED_MARKERS = re.compile(
    r"@generated|DO NOT EDIT|Code generated by|Autogenerated|auto-generated",
    re.IGNORECASE)
TRAILER_RE = re.compile(r"^([A-Za-z][A-Za-z0-9-]*(?:=|:\s))\s*(.*)$")


# --------------------------------------------------------------------------
# Diff parsing (shared by git, jj and diff-file modes)
# --------------------------------------------------------------------------


def parse_diff(diff: str) -> list[dict]:
    """Splits a unified diff into per-file records with stats and text."""
    files: list[dict] = []
    blocks = re.split(r"(?m)^(?=diff --git )", diff)
    for block in blocks:
        if not block.startswith("diff --git "):
            continue
        header = block.splitlines()[0]
        match = re.match(r"^diff --git a/(.*) b/(.*)$", header)
        old_path = new_path = None
        if match:
            old_path, new_path = match.group(1), match.group(2)
        status = "M"
        binary = False
        additions = deletions = hunks = 0
        in_body = False
        for line in block.splitlines()[1:]:
            if not in_body:
                if line.startswith("new file mode"):
                    status = "A"
                elif line.startswith("deleted file mode"):
                    status = "D"
                elif line.startswith("rename from "):
                    old_path = line[len("rename from "):]
                    status = "R"
                elif line.startswith("rename to "):
                    new_path = line[len("rename to "):]
                    status = "R"
                elif line.startswith("--- ") and not line.startswith("--- /dev/null"):
                    old_path = re.sub(r"^--- (a/)?", "", line)
                elif line.startswith("+++ ") and not line.startswith("+++ /dev/null"):
                    new_path = re.sub(r"^\+\+\+ (b/)?", "", line)
                elif line.startswith("Binary files") or line.startswith("GIT binary patch"):
                    binary = True
                elif line.startswith("@@"):
                    in_body = True
                    hunks += 1
                continue
            if line.startswith("@@"):
                hunks += 1
            elif line.startswith("+") and not line.startswith("+++ "):
                additions += 1
            elif line.startswith("-") and not line.startswith("--- "):
                deletions += 1
        path = new_path if status != "D" else old_path
        files.append({
            "path": path,
            "old_path": old_path if status == "R" else None,
            "status": status,
            "additions": additions,
            "deletions": deletions,
            "hunks": hunks,
            "binary": binary,
            "generated": bool(GENERATED_MARKERS.search(block[:4000])) and status != "D",
            "skipped": None,
            "_text": block,
        })
    return files


def apply_skips(files: list[dict], skip_globs: list[str]) -> None:
    for item in files:
        pattern = rc.glob_match(item["path"] or "", skip_globs)
        if pattern:
            item["skipped"] = f"matches skip glob {pattern}"
        elif item["generated"]:
            item["skipped"] = "generated-file marker"
        elif item["binary"]:
            item["skipped"] = "binary"


def join_diff(files: list[dict]) -> str:
    return "".join(item["_text"] for item in files if not item["skipped"])


def parse_trailers(body: str) -> dict[str, list[str]]:
    """Collects `Key: value` and `KEY=value` lines (git trailers, CL tags)."""
    trailers: dict[str, list[str]] = {}
    for line in body.splitlines():
        match = TRAILER_RE.match(line.strip())
        if not match:
            continue
        key = match.group(1).rstrip(":= ").strip()
        value = match.group(2).strip()
        if " " in key or not value:
            continue
        trailers.setdefault(key, []).append(value)
    return trailers


def triage(files: list[dict], config: dict) -> dict:
    depth_cfg = config["depth"]
    live = [f for f in files if not f["skipped"]]
    lines = sum(f["additions"] + f["deletions"] for f in live)
    reasons: list[str] = []
    suggested = "standard"
    deep_hits = [f["path"] for f in live if rc.glob_match(f["path"] or "", depth_cfg["deep_paths"])]
    if deep_hits:
        suggested = "deep"
        reasons.append(f"touches deep paths: {', '.join(deep_hits[:5])}")
    if lines >= depth_cfg["deep_min_lines"] or len(live) >= depth_cfg["deep_min_files"]:
        suggested = "deep"
        reasons.append(f"large change: {lines} lines across {len(live)} files")
    if (suggested != "deep" and lines <= depth_cfg["light_max_lines"]
            and len(live) <= depth_cfg["light_max_files"]):
        suggested = "light"
        reasons.append(f"tiny change: {lines} lines across {len(live)} files")
    kind = config["project"].get("kind") or "application"
    if kind not in rc.PROJECT_KINDS:
        reasons.append(f"unknown project.kind {kind!r}; treating as application")
        kind = "application"
    floor = {"script": "light", "application": "standard", "production": "deep"}[kind]
    order = {d: i for i, d in enumerate(rc.DEPTHS)}
    depth = max(suggested, floor, key=lambda d: order[d])
    if order[floor] > order[suggested]:
        reasons.append(f"project.kind={kind} raises the floor to {floor}")
    return {"suggested": suggested, "floor": floor, "depth": depth,
            "project_kind": kind, "reasons": reasons,
            "changed_lines": lines, "reviewed_files": len(live)}


# --------------------------------------------------------------------------
# VCS back ends
# --------------------------------------------------------------------------


def detect_default_branch(root: pathlib.Path, config: dict) -> tuple[str, str]:
    """Returns (name, ref) for the default branch."""
    name = (config.get("default_branch") or "").strip()
    if not name:
        sym = rc.try_run(["git", "symbolic-ref", "--quiet", "--short",
                          "refs/remotes/origin/HEAD"], cwd=root)
        if sym and sym.strip():
            name = sym.strip().split("/", 1)[-1]
    if not name:
        for candidate in ("main", "master", "trunk", "develop"):
            if rc.try_run(["git", "rev-parse", "--verify", "--quiet",
                           candidate + "^{commit}"], cwd=root) is not None:
                name = candidate
                break
    if not name:
        name = "main"
    for ref in (f"origin/{name}", name):
        if rc.try_run(["git", "rev-parse", "--verify", "--quiet",
                       ref + "^{commit}"], cwd=root) is not None:
            return name, ref
    return name, name


def git_commits(root: pathlib.Path, rng: str) -> list[dict]:
    out = rc.try_run(["git", "log", "--no-color", "--reverse",
                      "--format=%H%x1f%an%x1f%ae%x1f%s%x1f%b%x1e", rng], cwd=root)
    commits = []
    for record in (out or "").split("\x1e"):
        if not record.strip():
            continue
        parts = record.lstrip("\n").split("\x1f")
        if len(parts) < 5:
            continue
        sha, name, email, subject, body = parts[:5]
        commits.append({"sha": sha.strip(), "author_name": name, "author_email": email,
                        "subject": subject, "body": body.strip("\n"),
                        "trailers": parse_trailers(body)})
    return commits


def collect_git(root: pathlib.Path, args: argparse.Namespace, config: dict) -> dict:
    g = lambda *cmd: rc.run(["git", *cmd], cwd=root).strip()  # noqa: E731
    default_name, default_ref = detect_default_branch(root, config)
    branch = g("rev-parse", "--abbrev-ref", "HEAD")
    if branch == "HEAD":
        branch = "detached-" + g("rev-parse", "--short", "HEAD")

    head = args.head
    dirty_lines = g("status", "--porcelain", "--untracked-files=no")
    untracked = g("ls-files", "--others", "--exclude-standard").splitlines()
    worktree = False
    if head is None:
        if dirty_lines:
            worktree = True
        head = "HEAD"
    elif head.upper() == "WORKTREE":
        worktree = True
        head = "HEAD"
    head_sha = g("rev-parse", head + "^{commit}")

    base = args.base
    notes: list[str] = []
    if base is None:
        base = rc.try_run(["git", "merge-base", default_ref, head], cwd=root)
        base = base.strip() if base else None
        if base is None:
            base = head + "~1"
            notes.append(f"no merge-base with {default_ref}; using {base}")
        elif base == head_sha and not worktree:
            base = head + "~1"
            notes.append(f"{head} is on {default_name}; comparing against its parent")
        else:
            notes.append(f"base = merge-base({default_ref}, {head})")
    base_sha = g("rev-parse", base + "^{commit}")

    diff_target = [base_sha] if worktree else [base_sha, head_sha]
    diff = rc.run(["git", "diff", "--no-color", "--no-ext-diff", "-M", *diff_target], cwd=root)
    files = parse_diff(diff)
    commits = git_commits(root, f"{base_sha}..{head_sha}")
    if worktree:
        head_sha = f"{head_sha}+dirty-{hashlib.sha256(diff.encode()).hexdigest()[:8]}"

    pr = None
    pr_error = None
    if not args.no_pr and rc.have("gh"):
        try:
            out = rc.run(["gh", "pr", "view", "--json",
                          "number,title,body,labels,author,headRefName,baseRefName,url"],
                         cwd=root, timeout=30)
            data = json.loads(out)
            pr = {"number": data.get("number"), "title": data.get("title"),
                  "body": data.get("body"),
                  "labels": [l.get("name") for l in data.get("labels", [])],
                  "author_login": (data.get("author") or {}).get("login"),
                  "head_ref": data.get("headRefName"),
                  "base_ref": data.get("baseRefName"), "url": data.get("url")}
        except (subprocess.CalledProcessError, FileNotFoundError,
                subprocess.TimeoutExpired, json.JSONDecodeError) as exc:
            pr_error = f"gh pr view failed: {getattr(exc, 'stderr', exc)!s}".strip()[:300]

    return {
        "vcs": "git", "branch": branch, "default_branch": default_name,
        "base_ref": base, "head_ref": "WORKTREE" if worktree else head,
        "base_sha": base_sha, "head_sha": head_sha, "dirty": worktree,
        "untracked_files": untracked, "notes": notes,
        "files": files, "diff": diff, "commits": commits, "pr": pr, "pr_error": pr_error,
        "state_key": branch,
        "_ancestor": lambda prior: rc.try_run(
            ["git", "merge-base", "--is-ancestor", prior, head_sha.split("+")[0]],
            cwd=root) is not None,
        "_range_diff": lambda prior: rc.try_run(
            ["git", "diff", "--no-color", "--no-ext-diff", "-M", prior,
             *([] if worktree else [head_sha.split("+")[0]])], cwd=root),
        "_range_commits": lambda prior: git_commits(root, f"{prior}..{head_sha.split('+')[0]}"),
    }


def jj_commit_id(root: pathlib.Path, rev: str) -> str:
    out = rc.run(["jj", "log", "--no-graph", "-r", rev, "-T", "commit_id ++ \"\\n\""],
                 cwd=root).strip().splitlines()
    if len(out) != 1:
        raise SystemExit(f"jj revset {rev!r} resolved to {len(out)} commits; pass an explicit revision")
    return out[0]


def collect_jj(root: pathlib.Path, args: argparse.Namespace, config: dict) -> dict:
    head = args.head or "@"
    notes: list[str] = []
    if args.head is None:
        empty = rc.run(["jj", "log", "--no-graph", "-r", "@",
                        "-T", 'if(empty, "empty", "nonempty")'], cwd=root).strip()
        if empty == "empty":
            head = "@-"
            notes.append("working copy @ is empty; reviewing @- instead")
    base = args.base
    if base is None:
        base = f"fork_point(trunk() | ({head}))"
        if rc.try_run(["jj", "log", "--no-graph", "-r", base, "-T", "commit_id"], cwd=root) is None:
            base = f"({head})-"
            notes.append("fork_point() unavailable; base is the parent of head")
        else:
            notes.append(f"base = {base}")
    head_sha = jj_commit_id(root, head)
    base_sha = jj_commit_id(root, base)
    if base_sha == head_sha:
        # head is on trunk itself (fork_point == head): compare against its parent.
        base = f"({head})-"
        base_sha = jj_commit_id(root, base)
        notes.append("head is on trunk; comparing against its parent")
    diff = rc.run(["jj", "diff", "--git", "--from", base_sha, "--to", head_sha], cwd=root)
    files = parse_diff(diff)
    template = ('change_id ++ "\\x1f" ++ commit_id ++ "\\x1f" ++ author.name() ++ "\\x1f" ++ '
                'author.email() ++ "\\x1f" ++ description ++ "\\x1e"')
    out = rc.run(["jj", "log", "--no-graph", "--reversed", "-r", f"{base_sha}..{head_sha}",
                  "-T", template], cwd=root)
    commits = []
    for record in out.split("\x1e"):
        if not record.strip():
            continue
        change_id, commit_id, name, email, description = (record.lstrip("\n").split("\x1f") + [""] * 5)[:5]
        subject, _, body = description.partition("\n")
        commits.append({"sha": commit_id, "change_id": change_id, "author_name": name,
                        "author_email": email, "subject": subject.strip(),
                        "body": body.strip("\n"), "trailers": parse_trailers(description)})
    bookmarks = rc.run(["jj", "log", "--no-graph", "-r", head_sha, "-T", "bookmarks"], cwd=root).strip()
    change_short = rc.run(["jj", "log", "--no-graph", "-r", head_sha, "-T", "change_id.short()"], cwd=root).strip()
    branch = bookmarks.split()[0] if bookmarks else f"change-{change_short}"
    return {
        "vcs": "jj", "branch": branch, "default_branch": config.get("default_branch") or "trunk()",
        "base_ref": base, "head_ref": head, "base_sha": base_sha, "head_sha": head_sha,
        "dirty": False, "untracked_files": [], "notes": notes,
        "files": files, "diff": diff, "commits": commits, "pr": None, "pr_error": None,
        "state_key": branch,
        "_ancestor": lambda prior: rc.try_run(
            ["jj", "log", "--no-graph", "-r", f"({prior}) & ::{head_sha}", "-T", "commit_id"],
            cwd=root) not in (None, ""),
        "_range_diff": lambda prior: rc.try_run(
            ["jj", "diff", "--git", "--from", prior, "--to", head_sha], cwd=root),
        "_range_commits": lambda prior: [],
    }


def collect_diff_file(args: argparse.Namespace) -> dict:
    path = pathlib.Path(args.diff_file)
    diff = path.read_text(encoding="utf-8")
    digest = hashlib.sha256(diff.encode("utf-8")).hexdigest()[:12]
    pr = None
    if args.title or args.body:
        pr = {"number": None, "title": args.title or "", "body": args.body or "",
              "labels": [], "author_login": None, "head_ref": None, "base_ref": None, "url": None}
    return {
        "vcs": "diff", "branch": f"diff-{digest}", "default_branch": "",
        "base_ref": None, "head_ref": str(path), "base_sha": "unknown",
        "head_sha": f"diff-{digest}", "dirty": False, "untracked_files": [],
        "notes": [f"diff loaded from {path}; no VCS history available"],
        "files": parse_diff(diff), "diff": diff, "commits": [], "pr": pr, "pr_error": None,
        "state_key": f"diff-{digest}",
        "_ancestor": lambda prior: False, "_range_diff": lambda prior: None,
        "_range_commits": lambda prior: [],
    }


# --------------------------------------------------------------------------
# Main
# --------------------------------------------------------------------------


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("base", nargs="?", help="base revision (default: merge-base with the default branch)")
    parser.add_argument("head", nargs="?", help="head revision (default: HEAD, or WORKTREE when dirty)")
    parser.add_argument("--vcs", choices=("auto", "git", "jj", "diff"), default="auto")
    parser.add_argument("--diff-file", help="review a plain unified diff instead of a repository")
    parser.add_argument("--title", help="change title (diff mode)")
    parser.add_argument("--body", help="change description (diff mode)")
    parser.add_argument("--review-dir", help="state directory (default: $CODE_REVIEW_DIR or <root>/.review)")
    parser.add_argument("--out", help="output path (default: <review-dir>/tmp/change.json)")
    parser.add_argument("--no-pr", action="store_true", help="do not query gh for the pull request")
    parser.add_argument("--no-init", action="store_true", help="do not create the .review/ skeleton")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    root, detected = rc.find_repo_root()
    vcs = args.vcs
    if vcs == "auto":
        vcs = "diff" if args.diff_file else (detected or "")
    if not vcs:
        parser.error("no git or jj repository found; pass --diff-file to review a plain diff")
    if vcs == "diff" and not args.diff_file:
        parser.error("--vcs diff requires --diff-file")

    rd = rc.review_dir(root, args.review_dir)
    created = [] if args.no_init else rc.ensure_review_dir(rd)
    config = rc.load_config(rd)

    if vcs == "git":
        data = collect_git(root, args, config)
    elif vcs == "jj":
        data = collect_jj(root, args, config)
    else:
        data = collect_diff_file(args)

    files = data["files"]
    apply_skips(files, config["depth"]["skip_globs"])
    diff = join_diff(files)
    tri = triage(files, config)
    try:
        review_rel = str(rd.relative_to(root)) + "/"
    except ValueError:
        review_rel = None
    if review_rel:  # the skill's own state directory is never part of the change
        data["untracked_files"] = [p for p in data["untracked_files"] if not p.startswith(review_rel)]

    state_path = rd / "state" / (rc.safe_name(data["state_key"]) + ".json")
    prior = None
    rereview = None
    if state_path.exists():
        try:
            prior_state = rc.load_json(state_path)
        except (OSError, json.JSONDecodeError):
            prior_state = {}
        prior_head = (prior_state.get("head_sha") or "").split("+")[0]
        prior = {"path": str(state_path), "head_sha": prior_state.get("head_sha"),
                 "reviewed_at": prior_state.get("reviewed_at"),
                 "findings": len(prior_state.get("findings", []))}
        if prior_head and prior_head == data["head_sha"].split("+")[0] and not data["dirty"]:
            rereview = {"unchanged": True, "from": prior_head, "commits": [], "diff": ""}
        elif prior_head and data["_ancestor"](prior_head):
            inc_files = parse_diff(data["_range_diff"](prior_head) or "")
            apply_skips(inc_files, config["depth"]["skip_globs"])
            rereview = {"unchanged": False, "from": prior_head,
                        "commits": data["_range_commits"](prior_head),
                        "files": [f["path"] for f in inc_files if not f["skipped"]],
                        "diff": join_diff(inc_files)}
        elif prior_head:
            rereview = {"unchanged": False, "from": prior_head, "commits": [], "diff": "",
                        "note": "prior head is not an ancestor (rebased or amended); review the full change"}

    out_files = [{k: v for k, v in f.items() if not k.startswith("_")} for f in files]
    result = {
        "schema": "code-review/change/v1",
        "collected_at": rc.now_iso(),
        "vcs": data["vcs"],
        "repo_root": str(root),
        "review_dir": str(rd),
        "branch": data["branch"],
        "default_branch": data["default_branch"],
        "base_ref": data["base_ref"], "head_ref": data["head_ref"],
        "base_sha": data["base_sha"], "head_sha": data["head_sha"],
        "dirty": data["dirty"],
        "untracked_files": data["untracked_files"],
        "notes": data["notes"],
        "triage": tri,
        "stats": {
            "files": len(out_files),
            "reviewed_files": tri["reviewed_files"],
            "skipped_files": sum(1 for f in out_files if f["skipped"]),
            "additions": sum(f["additions"] for f in out_files if not f["skipped"]),
            "deletions": sum(f["deletions"] for f in out_files if not f["skipped"]),
            "hunks": sum(f["hunks"] for f in out_files if not f["skipped"]),
        },
        "changed_files": out_files,
        "diff": diff,
        "commits": data["commits"],
        "pr": data["pr"],
        "pr_error": data["pr_error"],
        "prior": prior,
        "rereview": rereview,
        "config_path": str(rd / "config.yaml"),
    }
    out_path = pathlib.Path(args.out) if args.out else rd / "tmp" / "change.json"
    rc.write_json(out_path, result)

    if not args.quiet:
        if created:
            if any(p.endswith("config.yaml") for p in created):
                rc.eprint(f"initialised {rd} (first run): {len(created)} files/dirs created; "
                          "see subskills/setup.md")
            else:
                rc.eprint(f"completed the {rd} skeleton (existing config.yaml kept): "
                          f"{len(created)} files/dirs created")
        rc.eprint(f"change.json -> {out_path}")
        rc.eprint(f"  {data['vcs']} {data['branch']}: {result['base_sha'][:12]}..{result['head_sha'][:12]}"
                  f"{' (dirty worktree)' if data['dirty'] else ''}")
        rc.eprint(f"  files: {result['stats']['reviewed_files']} reviewed, "
                  f"{result['stats']['skipped_files']} skipped; +{result['stats']['additions']} "
                  f"-{result['stats']['deletions']} in {result['stats']['hunks']} hunks")
        rc.eprint(f"  depth: {tri['depth']} ({'; '.join(tri['reasons']) or 'default'})")
        if rereview:
            if rereview.get("unchanged"):
                rc.eprint("  re-review: head unchanged since the last review")
            elif rereview.get("note"):
                rc.eprint(f"  re-review: prior head {rereview['from'][:12]}; {rereview['note']}")
            else:
                rc.eprint(f"  re-review: prior head {rereview['from'][:12]}; "
                          f"{len(rereview.get('commits', []))} new commits")
        for note in data["notes"]:
            rc.eprint(f"  note: {note}")
        if data["pr_error"]:
            rc.eprint(f"  note: {data['pr_error']}")
    print(out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
