#!/usr/bin/env python3
"""Self-test for the bug-hunt scripts: fingerprints, diff parsing, IDs, YAML.

Run after editing references/inversion.md or any script:
    python3 <skill dir>/scripts/test_scripts.py
"""

from __future__ import annotations

import sys

import collect_change
import detect_author
import review_common as rc

FINGERPRINT_CASES = [
    # (description, change.json fragment, expected family)
    ("claude co-author trailer",
     {"commits": [{"subject": "x", "body": "Co-authored-by: Claude <noreply@anthropic.com>", "author_email": "a@b.c", "author_name": "A"}]},
     "claude"),
    ("claude code footer",
     {"commits": [{"subject": "x", "body": "🤖 Generated with [Claude Code](https://claude.ai/code)", "author_email": "a@b.c", "author_name": "A"}]},
     "claude"),
    ("codex branch prefix",
     {"commits": [{"subject": "x", "body": "", "author_email": "a@b.c", "author_name": "A"}], "branch": "codex/add-retry"},
     "gpt"),
    ("copilot co-author",
     {"commits": [{"subject": "x", "body": "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>", "author_email": "a@b.c", "author_name": "A"}]},
     "gpt"),
    ("jules bot login",
     {"commits": [], "pr": {"author_login": "google-labs-jules[bot]", "labels": [], "title": "", "body": ""}},
     "gemini"),
    ("jetski TAG=agy",
     {"commits": [{"subject": "x", "body": "Some CL\n\nTAG=agy\nCONV=d00f38ff-5705-463c-978c-287289084fef", "author_email": "a@google.com", "author_name": "A"}]},
     "gemini"),
    ("explicit label wins over trailer",
     {"commits": [{"subject": "x", "body": "Co-authored-by: Claude <noreply@anthropic.com>", "author_email": "a@b.c", "author_name": "A"}],
      "pr": {"author_login": "dev", "labels": ["author-agent:gpt"], "title": "", "body": ""}},
     "gpt"),
    ("cursor is other",
     {"commits": [{"subject": "x", "body": "Co-authored-by: Cursor Agent <cursoragent@cursor.com>", "author_email": "a@b.c", "author_name": "A"}]},
     "other"),
    ("plain human commit is unknown, never guessed",
     {"commits": [{"subject": "Fix typo", "body": "Signed-off-by: Dev <dev@example.com>", "author_email": "dev@example.com", "author_name": "Dev"}]},
     "unknown"),
]

SAMPLE_DIFF = """diff --git a/src/a.py b/src/a.py
index 1111111..2222222 100644
--- a/src/a.py
+++ b/src/a.py
@@ -1,3 +1,4 @@
 def f():
-    return 1
+    return 2
+# note
diff --git a/old.txt b/new.txt
similarity index 90%
rename from old.txt
rename to new.txt
diff --git a/bin.dat b/bin.dat
new file mode 100644
Binary files /dev/null and b/bin.dat differ
diff --git a/gone.py b/gone.py
deleted file mode 100644
--- a/gone.py
+++ /dev/null
@@ -1,2 +0,0 @@
-x = 1
-y = 2
diff --git a/gen.py b/gen.py
new file mode 100644
--- /dev/null
+++ b/gen.py
@@ -0,0 +1,2 @@
+# @generated by tool
+X = 1
"""


def check(cond: bool, message: str, failures: list[str]) -> None:
    print(("ok   " if cond else "FAIL ") + message)
    if not cond:
        failures.append(message)


def main() -> int:
    failures: list[str] = []
    fingerprints = detect_author.load_fingerprints()
    for description, change, expected in FINGERPRINT_CASES:
        texts = detect_author.gather_texts(change)
        family, _, _ = detect_author.decide(detect_author.match_signals(texts, fingerprints))
        check(family == expected, f"fingerprint: {description} -> {family} (expected {expected})", failures)

    blind = detect_author.load_blind_spots()
    check(blind.get("claude") == ["off-by-one"] and blind.get("gpt") == ["auth-bypass"],
          f"blind spots parsed: {blind}", failures)

    routes = [
        (("human", "gemini"), "none"), (("claude", "gemini"), "cross-family"),
        (("gemini", "gemini"), "blind-spot"), (("gemini", ""), "blind-spot"),
    ]
    for (family, self_family), expected in routes:
        got = detect_author.route(family, self_family, {}, blind)["route"]
        check(got == expected, f"route {family}/{self_family or '<blank>'} -> {got}", failures)
    got = detect_author.route("gemini", "gemini", {"claude": "claude -p"}, blind)
    check(got["route"] == "inverted-cli" and got["inverted"], "route same family with claude command -> inverted-cli", failures)

    files = collect_change.parse_diff(SAMPLE_DIFF)
    by_path = {f["path"]: f for f in files}
    check(by_path["src/a.py"]["additions"] == 2 and by_path["src/a.py"]["deletions"] == 1, "diff: counts", failures)
    check(by_path["new.txt"]["status"] == "R" and by_path["new.txt"]["old_path"] == "old.txt", "diff: rename", failures)
    check(by_path["bin.dat"]["binary"] and by_path["bin.dat"]["status"] == "A", "diff: binary add", failures)
    check(by_path["gone.py"]["status"] == "D", "diff: delete", failures)
    check(by_path["gen.py"]["generated"], "diff: generated marker", failures)
    collect_change.apply_skips(files, ["**/*.lock"])
    check(by_path["gen.py"]["skipped"] == "generated-file marker" and by_path["bin.dat"]["skipped"] == "binary"
          and by_path["src/a.py"]["skipped"] is None, "skips: generated and binary only", failures)
    check("gen.py" not in collect_change.join_diff(files) and "src/a.py" in collect_change.join_diff(files),
          "join_diff drops skipped blocks", failures)

    check(rc.finding_id("c", "f", "a = 1\n  b = 2") == rc.finding_id("c", "f", "a=1b=2"), "finding_id ignores whitespace", failures)
    check(rc.finding_id("c", "f", "a") != rc.finding_id("c", "g", "a"), "finding_id depends on file", failures)
    check(rc.glob_match("c.lock", ["**/*.lock"]) and rc.glob_match("a/b/c.lock", ["**/*.lock"])
          and not rc.glob_match("src/dist/x", ["dist/**"]), "globs", failures)

    text = (rc.TEMPLATES_DIR / "config.yaml").read_text()
    mini = rc._MiniYaml(text).parse()
    check(mini["limits"]["max_findings"] == 8 and mini["depth"]["skip_globs"][0] == ".review/**"
          and mini["inversion"]["reviewers"]["claude"] == "", "mini yaml parses config template", failures)
    try:
        import yaml  # type: ignore
        check(yaml.safe_load(text) == mini, "mini yaml matches PyYAML", failures)
    except ImportError:
        print("skip PyYAML comparison (not installed)")

    trailers = collect_change.parse_trailers("Body\n\nCo-authored-by: X <x@y>\nTAG=agy\nnot a trailer line")
    check(trailers == {"Co-authored-by": ["X <x@y>"], "TAG": ["agy"]}, f"trailers: {trailers}", failures)

    print(f"\n{len(failures)} failure(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
